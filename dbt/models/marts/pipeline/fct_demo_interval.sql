select
    CAST(f.model_run_id AS String) AS `model_run_id`,
    CAST(f.record_key AS String) AS `record_key`,
    CAST(f.record_version_key AS String) AS `record_version_key`,
    CAST(f.row_hash AS String) AS `row_hash`,
    CAST(f.calculated_at AS DateTime64(3,'UTC')) AS `calculated_at`,
    CAST(f.rule_version AS String) AS `rule_version`,
    CAST(f.input_cutoff_at AS DateTime64(3,'UTC')) AS `input_cutoff_at`,
    CAST(f.source_published_at AS Nullable(DateTime64(3,'UTC'))) AS `source_published_at`,
    CAST(f.source_version_keys AS Array(String)) AS `source_version_keys`,
    CAST(f.demo_interval_key AS String) AS `demo_interval_key`,
    CAST(f.demo_journey_key AS String) AS `demo_journey_key`,
    CAST(f.tenant_id AS String) AS `tenant_id`,
    CAST(f.start_action_key AS String) AS `start_action_key`,
    CAST(f.end_action_key AS String) AS `end_action_key`,
    CAST(f.start_action_id AS Int64) AS `start_action_id`,
    CAST(f.end_action_id AS Int64) AS `end_action_id`,
    CAST(f.opportunity_id AS Nullable(Int64)) AS `opportunity_id`,
    CAST(f.opportunity_key AS Nullable(String)) AS `opportunity_key`,
    CAST(f.company_key AS Nullable(String)) AS `company_key`,
    CAST(f.company_version_key AS Nullable(String)) AS `company_version_key`,
    CAST(f.sale_type_id AS Nullable(Int64)) AS `sale_type_id`,
    CAST(f.sale_type_key AS Nullable(String)) AS `sale_type_key`,
    CAST(f.sale_type_version_key AS Nullable(String)) AS `sale_type_version_key`,
    CAST(f.team_key AS Nullable(String)) AS `team_key`,
    CAST(f.team_version_key AS Nullable(String)) AS `team_version_key`,
    CAST(f.interval_kind AS String) AS `interval_kind`,
    CAST(f.from_demo_step AS String) AS `from_demo_step`,
    CAST(f.to_demo_step AS String) AS `to_demo_step`,
    CAST(f.started_at AS DateTime64(3,'UTC')) AS `started_at`,
    CAST(f.ended_at AS DateTime64(3,'UTC')) AS `ended_at`,
    CAST(f.elapsed_duration_seconds AS Float64) AS `elapsed_duration_seconds`,
    CAST(f.elapsed_duration_days AS Float64) AS `elapsed_duration_days`,
    CAST(f.time_basis AS String) AS `time_basis`,
    CAST(f.link_status AS String) AS `link_status`,
    CAST(f.calculation_status AS String) AS `calculation_status`,
    CAST(f.status_reason AS Nullable(String)) AS `status_reason`,
    CAST(date_started_date_key.date_key AS UInt32) AS `started_date_key`,
    CAST(date_ended_date_key.date_key AS UInt32) AS `ended_date_key`
from {{ ref('int_demo_intervals') }} f left join {{ ref('dim_date') }} date_started_date_key on f.model_run_id=date_started_date_key.model_run_id and date_started_date_key.calendar_date=toDate(f.started_at,'Europe/Paris') left join {{ ref('dim_date') }} date_ended_date_key on f.model_run_id=date_ended_date_key.model_run_id and date_ended_date_key.calendar_date=toDate(f.ended_at,'Europe/Paris')
