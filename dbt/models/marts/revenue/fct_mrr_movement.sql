select
    CAST(f.model_run_id AS String) AS `model_run_id`,
    CAST(f.record_key AS String) AS `record_key`,
    CAST(f.record_version_key AS String) AS `record_version_key`,
    CAST(f.row_hash AS String) AS `row_hash`,
    CAST(f.calculated_at AS DateTime64(3,'UTC')) AS `calculated_at`,
    CAST(f.rule_version AS String) AS `rule_version`,
    CAST(f.input_cutoff_at AS DateTime64(3,'UTC')) AS `input_cutoff_at`,
    CAST(f.source_published_at AS Nullable(DateTime64(3,'UTC'))) AS `source_published_at`,
    CAST(f.source_version_keys AS Array(String)) AS `source_version_keys`,
    CAST(f.movement_contribution_key AS String) AS `movement_contribution_key`,
    CAST(f.tenant_id AS String) AS `tenant_id`,
    CAST(f.client_context_key AS String) AS `client_context_key`,
    CAST(f.company_id AS Int64) AS `company_id`,
    CAST(f.company_key AS String) AS `company_key`,
    CAST(f.company_version_key AS Nullable(String)) AS `company_version_key`,
    CAST(f.month_date AS Date) AS `month_date`,
    CAST(f.month_end_date AS Date) AS `month_end_date`,
    CAST(f.previous_month_end_date AS Date) AS `previous_month_end_date`,
    CAST(f.movement_kind AS String) AS `movement_kind`,
    CAST(f.new_mrr_component AS Nullable(String)) AS `new_mrr_component`,
    CAST(f.sum_new_mrr AS Nullable(Decimal(38,4))) AS `sum_new_mrr`,
    CAST(f.sum_departure_mrr AS Nullable(Decimal(38,4))) AS `sum_departure_mrr`,
    CAST(f.sum_contraction_mrr AS Nullable(Decimal(38,4))) AS `sum_contraction_mrr`,
    CAST(f.sum_candidate_new_mrr AS Nullable(Decimal(38,4))) AS `sum_candidate_new_mrr`,
    CAST(f.sum_candidate_departure_mrr AS Nullable(Decimal(38,4))) AS `sum_candidate_departure_mrr`,
    CAST(f.sum_candidate_contraction_mrr AS Nullable(Decimal(38,4))) AS `sum_candidate_contraction_mrr`,
    CAST(f.is_portfolio_entrant AS Nullable(Bool)) AS `is_portfolio_entrant`,
    CAST(f.is_departure AS Nullable(Bool)) AS `is_departure`,
    CAST(f.is_contraction AS Nullable(Bool)) AS `is_contraction`,
    CAST(f.is_active_before AS Nullable(Bool)) AS `is_active_before`,
    CAST(f.is_active_after AS Nullable(Bool)) AS `is_active_after`,
    CAST(f.first_acquisition_status AS String) AS `first_acquisition_status`,
    CAST(f.is_comparable AS Nullable(Bool)) AS `is_comparable`,
    CAST(f.commercial_link_status AS String) AS `commercial_link_status`,
    CAST(f.source_lineage_status AS String) AS `source_lineage_status`,
    CAST(f.calculation_status AS String) AS `calculation_status`,
    CAST(f.status_reason AS Nullable(String)) AS `status_reason`,
    CAST(date_month_date_key.date_key AS UInt32) AS `month_date_key`,
    CAST(date_closing_date_key.date_key AS UInt32) AS `closing_date_key`,
    CAST(date_previous_closing_date_key.date_key AS UInt32) AS `previous_closing_date_key`
from {{ ref('int_mrr_movements') }} f left join {{ ref('dim_date') }} date_month_date_key on f.model_run_id=date_month_date_key.model_run_id and date_month_date_key.calendar_date=toDate(f.month_date,'Europe/Paris') left join {{ ref('dim_date') }} date_closing_date_key on f.model_run_id=date_closing_date_key.model_run_id and date_closing_date_key.calendar_date=toDate(f.month_end_date,'Europe/Paris') left join {{ ref('dim_date') }} date_previous_closing_date_key on f.model_run_id=date_previous_closing_date_key.model_run_id and date_previous_closing_date_key.calendar_date=toDate(f.previous_month_end_date,'Europe/Paris')
